def generate(output_dir: str) -> None:
    _generate_country(output_dir)
    _generate_province(output_dir)
    _generate_city(output_dir)


def _generate_country(output_dir: str) -> None:
    path = f"{output_dir}/country.csv"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "name", "image_url"])
        for i, name in enumerate(COUNTRIES, 1):
            w.writerow([i, name, f"https://images.turip.com/country/{i}.jpg"])
    print(f"  country.csv       : {config.COUNTRY_COUNT}행")


def _generate_province(output_dir: str) -> None:
    path = f"{output_dir}/province.csv"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "name"])
        for i, name in enumerate(PROVINCES, 1):
            w.writerow([i, name])
    print(f"  province.csv      : {config.PROVINCE_COUNT}행")


def _generate_city(output_dir: str) -> None:
    """
    대한민국(country_id=1)만 province_id 세팅, 나머지는 빈 문자열(→ NULL).
    LOAD DATA 시 SET province_id = NULLIF(@province_id, '') 처리 필요.
    """
    korea_country_id = COUNTRIES.index("대한민국") + 1  # 1-based = 1
    count = 0

    path = f"{output_dir}/city.csv"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "country_id", "province_id", "name", "image_url"])
        city_id = 1
        for country_id, country_name in enumerate(COUNTRIES, 1):
            for city_data in CITY_MAP[country_name]:
                if country_id == korea_country_id:
                    city_name, province_id = city_data
                else:
                    city_name, province_id = city_data, ""  # NULL
                w.writerow([
                    city_id, country_id, province_id,
                    city_name,
                    f"https://images.turip.com/city/{city_id}.jpg",
                ])
                city_id += 1
                count += 1
    print(f"  city.csv          : {count}행")
